"""Tests for multi-language Tree-sitter handlers and LanguageRegistry."""

from __future__ import annotations

from src.data.languages import LanguageRegistry
from src.data.preprocessing import has_valid_syntax


class TestLanguageHandlers:
    """Test Tree-sitter parsing and syntax validation across languages."""

    def test_supported_languages(self) -> None:
        supported = LanguageRegistry.supported_languages()
        assert "python" in supported
        assert "javascript" in supported
        assert "java" in supported
        assert "go" in supported

    def test_extension_lookup(self) -> None:
        assert LanguageRegistry.get(".py").name == "python"
        assert LanguageRegistry.get(".js").name == "javascript"
        assert LanguageRegistry.get(".ts").name == "javascript"
        assert LanguageRegistry.get(".java").name == "java"
        assert LanguageRegistry.get(".go").name == "go"

    def test_python_syntax_validation(self) -> None:
        valid_py = "def add(a: int, b: int) -> int:\n    return a + b\n"
        invalid_py = "def add(a, b\n    return"
        assert has_valid_syntax(valid_py, language="python")
        assert not has_valid_syntax(invalid_py, language="python")

    def test_javascript_syntax_validation(self) -> None:
        valid_js = "function add(a, b) { return a + b; }"
        invalid_js = "function add(a, b { return a + b"
        assert has_valid_syntax(valid_js, language="javascript")
        assert not has_valid_syntax(invalid_js, language="javascript")

    def test_java_syntax_validation(self) -> None:
        valid_java = "public class Calc { public int add(int a, int b) { return a + b; } }"
        invalid_java = "public class Calc { int add("
        assert has_valid_syntax(valid_java, language="java")
        assert not has_valid_syntax(invalid_java, language="java")

    def test_go_syntax_validation(self) -> None:
        valid_go = "package main\n\nfunc Add(a, b int) int {\n\treturn a + b\n}"
        invalid_go = "package main\nfunc Add(a, b"
        assert has_valid_syntax(valid_go, language="go")
        assert not has_valid_syntax(invalid_go, language="go")

    def test_auto_gen_detection(self) -> None:
        handler = LanguageRegistry.get("python")
        assert handler.is_auto_generated("# Auto-generated by protoc. Do not edit.\ncode = 1")
        assert not handler.is_auto_generated("def my_func(): pass")
