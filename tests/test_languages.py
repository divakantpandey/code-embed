"""Tests for multi-language Tree-sitter handlers and LanguageRegistry."""

from __future__ import annotations

from src.data.languages import LanguageRegistry
from src.data.preprocessing import has_valid_syntax


class TestLanguageHandlers:
    """Test Tree-sitter parsing and syntax validation across languages."""

    def test_supported_languages(self) -> None:
        supported = LanguageRegistry.supported_languages()
        assert "python" in supported
        assert "javascript" in supported
        assert "java" in supported
        assert "go" in supported
        assert "ruby" in supported
        assert "php" in supported

    def test_extension_lookup(self) -> None:
        assert LanguageRegistry.get(".py").name == "python"
        assert LanguageRegistry.get(".js").name == "javascript"
        assert LanguageRegistry.get(".ts").name == "javascript"
        assert LanguageRegistry.get(".java").name == "java"
        assert LanguageRegistry.get(".go").name == "go"
        assert LanguageRegistry.get(".rb").name == "ruby"
        assert LanguageRegistry.get(".php").name == "php"

    def test_python_syntax_validation(self) -> None:
        valid_py = "def add(a: int, b: int) -> int:\n    return a + b\n"
        invalid_py = "def add(a, b\n    return"
        assert has_valid_syntax(valid_py, language="python")
        assert not has_valid_syntax(invalid_py, language="python")

    def test_javascript_syntax_validation(self) -> None:
        valid_js = "function add(a, b) { return a + b; }"
        invalid_js = "function add(a, b { return a + b"
        assert has_valid_syntax(valid_js, language="javascript")
        assert not has_valid_syntax(invalid_js, language="javascript")

    def test_java_syntax_validation(self) -> None:
        valid_java = "public class Calc { public int add(int a, int b) { return a + b; } }"
        invalid_java = "public class Calc { int add("
        assert has_valid_syntax(valid_java, language="java")
        assert not has_valid_syntax(invalid_java, language="java")

    def test_go_syntax_validation(self) -> None:
        valid_go = "package main\n\nfunc Add(a, b int) int {\n\treturn a + b\n}"
        invalid_go = "package main\nfunc Add(a, b"
        assert has_valid_syntax(valid_go, language="go")
        assert not has_valid_syntax(invalid_go, language="go")

    def test_ruby_syntax_validation(self) -> None:
        valid_rb = "def add(a, b)\n  a + b\nend"
        invalid_rb = "def add(a, b\n  a +"
        assert has_valid_syntax(valid_rb, language="ruby")
        assert not has_valid_syntax(invalid_rb, language="ruby")

    def test_php_syntax_validation(self) -> None:
        valid_php = "<?php\nfunction add($a, $b) {\n    return $a + $b;\n}"
        invalid_php = "<?php\nfunction add($a, $b {"
        assert has_valid_syntax(valid_php, language="php")
        assert not has_valid_syntax(invalid_php, language="php")

    def test_has_function_definition_across_languages(self) -> None:
        from src.data.preprocessing import has_function_definition

        assert has_function_definition("def foo(): pass", language="python")
        assert not has_function_definition("x = 10", language="python")

        assert has_function_definition("package p\nfunc Foo() {}", language="go")
        assert not has_function_definition("package p\nvar x = 1", language="go")

        assert has_function_definition("class A { int foo() { return 1; } }", language="java")
        assert not has_function_definition("class A { int x = 1; }", language="java")

        assert has_function_definition("function foo() { return 1; }", language="javascript")
        assert not has_function_definition("const x = 1;", language="javascript")

        assert has_function_definition("def foo\n  1\nend", language="ruby")
        assert not has_function_definition("x = 1", language="ruby")

        assert has_function_definition("<?php\nfunction foo() { return 1; }", language="php")
        assert not has_function_definition("<?php\n$x = 1;", language="php")

    def test_comment_ratio_across_languages(self) -> None:
        from src.data.preprocessing import compute_comment_ratio

        # Python (#)
        assert compute_comment_ratio("# line 1\n# line 2\nx = 1", language="python") == 2 / 3
        # Go (//)
        assert compute_comment_ratio("// line 1\n// line 2\nvar x = 1", language="go") == 2 / 3
        # Java (//, /*, *)
        assert compute_comment_ratio("/* comment */\nint x = 1;", language="java") == 0.5
        # Ruby (#)
        assert compute_comment_ratio("# comment\nx = 1", language="ruby") == 0.5
        # PHP (//, #)
        assert compute_comment_ratio("// comment\n# comment 2\n$x = 1;", language="php") == 2 / 3

    def test_auto_gen_detection(self) -> None:
        handler = LanguageRegistry.get("python")
        assert handler.is_auto_generated("# Auto-generated by protoc. Do not edit.\ncode = 1")
        assert not handler.is_auto_generated("def my_func(): pass")

    def test_extract_docstring_and_code(self) -> None:
        for lang in ["python", "javascript", "java", "go", "ruby", "php"]:
            handler = LanguageRegistry.get(lang)
            item = {
                "func_documentation_string": f"Doc for {lang}",
                "func_code_string": f"Code for {lang}",
            }
            doc, code = handler.extract_docstring_and_code(item)
            assert doc == f"Doc for {lang}"
            assert code == f"Code for {lang}"
