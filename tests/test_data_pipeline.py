class TestPreprocessingFilters:
    """Test individual syntax and quality filtering predicates."""

    def test_has_valid_syntax(self) -> None:
        valid_code = "def add(x, y):\n    return x + y"
        invalid_code = "def bad_syntax(x, y: return x +"
        assert has_valid_syntax(valid_code) is True
        assert has_valid_syntax(invalid_code) is False

    def test_has_function_definition(self) -> None:
        with_func = "def square(x):\n    return x * x"
        with_async_func = "async def fetch():\n    pass"
        without_func = "x = 42\ny = x + 10\nprint(y)"
        assert has_function_definition(with_func) is True
        assert has_function_definition(with_async_func) is True
        assert has_function_definition(without_func) is False

    def test_is_auto_generated(self) -> None:
        auto_gen_1 = "# This file is auto-generated by protoc\ndef pb(): pass"
        auto_gen_2 = "# @generated by thrift\nx = 1"
        human_code = 'def fib(n):\n    """Compute fibonacci."""\n    return n'
        assert is_auto_generated(auto_gen_1) is True
        assert is_auto_generated(auto_gen_2) is True
        assert is_auto_generated(human_code) is False

    def test_compute_comment_ratio(self) -> None:
        mostly_comments = "# line 1\n# line 2\n# line 3\nx = 1"
        assert compute_comment_ratio(mostly_comments) == 0.75

        no_comments = "x = 1\ny = 2\nz = 3"
        assert compute_comment_ratio(no_comments) == 0.0

    def test_preprocess_code_normalization(self) -> None:
        dirty_code = "  \n\ndef foo():\n\n\n\n    return 1\n\n  "
        cleaned = preprocess_code(dirty_code)
        assert cleaned == "def foo():\n\n    return 1"

    def test_deduplicate_minhash(self) -> None:
        data = {
            "code": [
                "def solve(a, b):\n    return a + b",
                "def solve(a, b):\n    return a + b",  # exact duplicate
                "def distinct_function(z):\n    return z * 10",
            ]
        }
        ds = Dataset.from_dict(data)
        deduped = deduplicate_minhash(ds, column="code", threshold=0.8)
        assert len(deduped) == 2

    def test_apply_filters_with_config_and_kwargs(self, dummy_tokenizer: Any) -> None:
        data = {
            "code": [
                "def valid_func(a, b):\n    return a + b",
                "# auto-generated\ndef auto_func():\n    pass",  # auto-generated
                "def bad_syntax(: pass",  # invalid syntax
                "x = 1\ny = 2\nz = 3",  # no function def
                "# 1\n# 2\n# 3\ndef foo(): pass",  # high comment ratio
                "def tiny(): return 1",  # short tokens test
            ]
        }
        ds = Dataset.from_dict(data)

        # Call with kwargs
        filtered = apply_filters(
            dataset=ds,
            tokenizer=dummy_tokenizer,
            code_column="code",
            min_tokens=3,
            max_tokens=100,
            require_valid_syntax=True,
            require_function_def=True,
            max_comment_ratio=0.5,
        )
        assert len(filtered) == 2
        codes = [row["code"] for row in filtered]
        assert "def valid_func(a, b):\n    return a + b" in codes
        assert "def tiny(): return 1" in codes

        # Call with config dict
        cfg = {
            "min_tokens": 5,
            "max_tokens": 100,
            "require_valid_syntax": True,
            "require_function_def": True,
            "max_comment_ratio": 0.5,
        }
        filtered_cfg = apply_filters(
            dataset=ds,
            tokenizer=dummy_tokenizer,
            config=cfg,
            code_column="code",
        )
        assert len(filtered_cfg) == 1
        assert filtered_cfg[0]["code"] == "def valid_func(a, b):\n    return a + b"


class TestDatasetsAndCollators:
    """Test dataset and collator integrations."""

    def test_contrastive_dataset(self) -> None:
        codes = ["def a(): pass", "def b(): pass"]
        ds = ContrastiveDataset(codes)
        assert len(ds) == 2
        item = ds[0]
        assert item["text"] == "def a(): pass"

    def test_codesearchnet_dataset(self) -> None:
        queries = ["query 1", "query 2"]
        codes = ["code 1", "code 2"]
        ds = CodeSearchNetDataset(queries, codes)
        assert len(ds) == 2
        assert ds[0] == {"query": "query 1", "code": "code 1"}

    def test_triplet_dataset(self) -> None:
        queries = ["q1"]
        positives = ["p1"]
        negatives = ["n1"]
        ds = TripletDataset(queries, positives, negatives)
        assert len(ds) == 1
        assert ds[0] == {"query": "q1", "positive": "p1", "negative": "n1"}

    def test_embedding_collator(self, dummy_tokenizer: Any) -> None:
        collator = EmbeddingCollator(tokenizer=dummy_tokenizer, max_length=16)
        batch = ["def a(): pass", "def b(): pass"]
        res = collator(batch)
        assert "input_ids" in res
        assert "attention_mask" in res
        assert res["input_ids"].shape[0] == 2

    def test_pair_collator(self, dummy_tokenizer: Any) -> None:
        collator = PairCollator(tokenizer=dummy_tokenizer, max_length=16)
        batch = [
            {"query": "compute sum", "code": "def sum(a, b): return a + b"},
            {"query": "sort array", "code": "def sort(arr): return sorted(arr)"},
        ]
        res = collator(batch)
        assert "query_input_ids" in res
        assert "code_input_ids" in res
        assert res["query_input_ids"].shape[0] == 2
        assert res["code_input_ids"].shape[0] == 2


class TestHardNegatives:
    """Test BM25 negative mining."""

    def test_bm25_negative_miner(self) -> None:
        corpus = [
            "def binary_search(arr, target): pass",
            "def quick_sort(arr): pass",
            "def bubble_sort(arr): pass",
            "def merge_sort(arr): pass",
        ]
        miner = BM25NegativeMiner(corpus=corpus, top_k=3)
        # Search for sorting, excluding quick_sort (index 1)
        neg = miner.mine_negative_for_query(query="sorting algorithm", positive_idx=1)
        assert isinstance(neg, str)
        assert neg in corpus
        assert neg != corpus[1]
