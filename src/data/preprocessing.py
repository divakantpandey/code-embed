"""Data quality filters and preprocessing for Python code snippets.

Provides individual filter predicates, a preprocessing normaliser, and a
pipeline that applies all filters to a HuggingFace ``datasets.Dataset``.
MinHash-based deduplication uses the ``datasketch`` library.
"""

from __future__ import annotations

import ast
import logging
import re
from typing import Any

from datasets import Dataset
from datasketch import MinHash, MinHashLSH
from transformers import PreTrainedTokenizerBase

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Common auto-generation markers found at the top of machine-generated files
# ---------------------------------------------------------------------------
_AUTO_GEN_MARKERS: list[str] = [
    "auto-generated",
    "autogenerated",
    "automatically generated",
    "generated by",
    "do not edit",
    "do not modify",
    "machine generated",
    "this file is generated",
    "code generated by",
    "@generated",
]


# ── Individual filter predicates ──────────────────────────────────────────


def filter_by_length(
    code: str,
    min_tokens: int,
    max_tokens: int,
    tokenizer: PreTrainedTokenizerBase,
) -> bool:
    """Return ``True`` if *code* has between *min_tokens* and *max_tokens* tokens.

    Uses *tokenizer* to tokenize the code (no special tokens) and checks the
    resulting count is within the closed interval ``[min_tokens, max_tokens]``.
    """
    token_ids = tokenizer.encode(code, add_special_tokens=False)
    return min_tokens <= len(token_ids) <= max_tokens


def has_valid_syntax(code: str, language: str = "python") -> bool:
    """Return ``True`` if *code* parses as valid syntax in *language* via Tree-sitter / AST."""
    from src.data.languages.registry import LanguageRegistry

    return LanguageRegistry.get(language).has_valid_syntax(code)


def has_function_definition(code: str) -> bool:
    """Return ``True`` if *code* contains at least one ``def`` statement.

    Uses :func:`ast.parse` so it only counts real function definitions, not
    occurrences of the word *def* in strings or comments.
    """
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return False
    return any(isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) for node in ast.walk(tree))


def is_auto_generated(code: str) -> bool:
    """Return ``True`` if *code* appears to be machine-generated.

    Inspects the first five non-empty lines and checks for common auto-gen
    markers (case-insensitive).
    """
    header_lines = []
    for line in code.splitlines():
        stripped = line.strip()
        if stripped:
            header_lines.append(stripped.lower())
        if len(header_lines) >= 5:
            break

    header_text = " ".join(header_lines)
    return any(marker in header_text for marker in _AUTO_GEN_MARKERS)


def compute_comment_ratio(code: str) -> float:
    """Return the ratio of comment lines to total non-blank lines in *code*.

    A "comment line" is any line whose first non-whitespace character is ``#``.
    If the code has no non-blank lines the ratio is ``0.0``.
    """
    lines = code.splitlines()
    non_blank = [line for line in lines if line.strip()]
    if not non_blank:
        return 0.0
    comment_lines = sum(1 for line in non_blank if line.lstrip().startswith("#"))
    return comment_lines / len(non_blank)


# ── Preprocessing / normalisation ─────────────────────────────────────────

# Matches 3+ consecutive blank lines (keeping at most 2)
_EXCESSIVE_BLANKS_RE = re.compile(r"\n{3,}")


def preprocess_code(code: str) -> str:
    """Normalise whitespace in *code*.

    * Strips trailing whitespace from every line.
    * Collapses runs of 3+ blank lines into exactly two blank lines.
    * Strips leading/trailing blank lines from the whole snippet.
    """
    # Strip trailing whitespace per line
    lines = [line.rstrip() for line in code.splitlines()]
    text = "\n".join(lines)
    # Collapse excessive blank lines
    text = _EXCESSIVE_BLANKS_RE.sub("\n\n", text)
    return text.strip()


# ── Full filter pipeline ──────────────────────────────────────────────────


def apply_filters(
    dataset: Dataset,
    tokenizer: PreTrainedTokenizerBase,
    config: dict[str, Any] | None = None,
    *,
    code_column: str = "whole_func_string",
    min_tokens: int | None = None,
    max_tokens: int | None = None,
    require_valid_syntax: bool | None = None,
    require_function_def: bool | None = None,
    max_comment_ratio: float | None = None,
) -> Dataset:
    """Apply all quality filters to *dataset* and return the filtered dataset.

    Parameters
    ----------
    dataset:
        A HuggingFace :class:`~datasets.Dataset` with at least a column named
        *code_column*.
    tokenizer:
        Tokenizer used for token-length checks.
    config:
        Optional ``data.preprocessing`` section of the training config. Expected
        keys: ``min_tokens``, ``max_tokens``, ``require_valid_syntax``,
        ``require_function_def``, ``max_comment_ratio``.
    code_column:
        Name of the column containing Python source code.
    min_tokens:
        Minimum number of tokens required in the code snippet. Overrides *config*.
    max_tokens:
        Maximum number of tokens allowed in the code snippet. Overrides *config*.
    require_valid_syntax:
        Whether to reject code with syntax errors. Overrides *config*.
    require_function_def:
        Whether to require at least one function definition. Overrides *config*.
    max_comment_ratio:
        Maximum allowed ratio of comment lines. Overrides *config*.

    Returns
    -------
    datasets.Dataset
        The filtered dataset (rows that pass **all** predicates).
    """
    cfg = config or {}
    resolved_min_tokens: int = min_tokens if min_tokens is not None else cfg.get("min_tokens", 10)
    resolved_max_tokens: int = max_tokens if max_tokens is not None else cfg.get("max_tokens", 512)
    resolved_require_syntax: bool = (
        require_valid_syntax
        if require_valid_syntax is not None
        else cfg.get("require_valid_syntax", True)
    )
    resolved_require_func: bool = (
        require_function_def
        if require_function_def is not None
        else cfg.get("require_function_def", True)
    )
    resolved_max_comment_ratio: float = (
        max_comment_ratio if max_comment_ratio is not None else cfg.get("max_comment_ratio", 0.5)
    )

    initial_len = len(dataset)
    logger.info("Applying quality filters to %d examples …", initial_len)

    def _passes(example: dict[str, Any]) -> bool:
        code: str = example.get(code_column, "")
        if not code or not isinstance(code, str):
            return False

        # Auto-generated check (reject)
        if is_auto_generated(code):
            return False

        # Token-length bounds
        if not filter_by_length(code, resolved_min_tokens, resolved_max_tokens, tokenizer):
            return False

        # Syntax check
        if resolved_require_syntax and not has_valid_syntax(code):
            return False

        # Function definition check
        if resolved_require_func and not has_function_definition(code):
            return False

        # Comment ratio
        return compute_comment_ratio(code) <= resolved_max_comment_ratio

    filtered = dataset.filter(_passes, desc="Filtering")
    logger.info(
        "Filtering complete: %d → %d examples (removed %d).",
        initial_len,
        len(filtered),
        initial_len - len(filtered),
    )
    return filtered


# ── MinHash deduplication ─────────────────────────────────────────────────


def _build_minhash(text: str, num_perm: int) -> MinHash:
    """Create a :class:`MinHash` for *text* using word-level 3-grams."""
    mh = MinHash(num_perm=num_perm)
    words = text.split()
    # Build shingles (word-level trigrams)
    for i in range(len(words) - 2):
        shingle = " ".join(words[i : i + 3])
        mh.update(shingle.encode("utf-8"))
    # Fallback: if text is very short, just hash each word
    if len(words) < 3:
        for w in words:
            mh.update(w.encode("utf-8"))
    return mh


def deduplicate_minhash(
    dataset: Dataset,
    column: str = "whole_func_string",
    threshold: float = 0.8,
    num_perm: int = 128,
) -> Dataset:
    """Remove near-duplicate rows from *dataset* using MinHash LSH.

    Parameters
    ----------
    dataset:
        A HuggingFace :class:`~datasets.Dataset`.
    column:
        Name of the text column to compare.
    threshold:
        Jaccard-similarity threshold above which two rows are considered
        duplicates.
    num_perm:
        Number of MinHash permutations (higher ⇒ more accurate but slower).

    Returns
    -------
    datasets.Dataset
        Dataset with near-duplicates removed (first occurrence kept).
    """
    logger.info(
        "Running MinHash dedup (threshold=%.2f, num_perm=%d) on %d examples …",
        threshold,
        num_perm,
        len(dataset),
    )

    lsh = MinHashLSH(threshold=threshold, num_perm=num_perm)
    keep_indices: list[int] = []

    for idx in range(len(dataset)):
        text: str = dataset[idx][column]
        mh = _build_minhash(text, num_perm)

        # Check for near-duplicate already in the index
        if not lsh.query(mh):
            # No near-duplicate found – keep this row
            key = str(idx)
            lsh.insert(key, mh)
            keep_indices.append(idx)

    deduped = dataset.select(keep_indices)
    logger.info(
        "Dedup complete: %d → %d examples (removed %d duplicates).",
        len(dataset),
        len(deduped),
        len(dataset) - len(deduped),
    )
    return deduped
